function refreshOwned(path) {
  if(customOutputRoot) {
    mkdirSync(path); // A collision is never an excuse to delete another package.
    writeFileSync(join(path,'.sapflow-owned'),'Generated by scripts/build-native.mjs\n',{flag:'wx'});return path;
  }
  if(existsSync(path)&&!existsSync(join(path,'.sapflow-owned')))throw Error('Refusing to replace unowned native output');
  rmSync(path,{recursive:true,force:true});mkdirSync(path,{recursive:true});writeFileSync(join(path,'.sapflow-owned'),'Generated by scripts/build-native.mjs\n');return path;
}
async function jnaJar() {
  const path=join(root,'target/native-tooling/jna-5.19.1.jar'),expected='4fb141dd8ef6b0585ffceea4bc49602fbc6312fa977e2c488794ea3e6aafecae';
  if(!existsSync(path)) {
    const response=await fetch('https://repo.maven.apache.org/maven2/net/java/dev/jna/jna/5.19.1/jna-5.19.1.jar',{redirect:'error',signal:AbortSignal.timeout(30000)});
    if(!response.ok)throw Error('Could not obtain the pinned JNA dependency');
    const data=Buffer.from(await response.arrayBuffer());if(createHash('sha256').update(data).digest('hex')!==expected)throw Error('JNA checksum mismatch');
    mkdirSync(join(root,'target/native-tooling'),{recursive:true});writeFileSync(path,data);
  }
  if(createHash('sha256').update(readFileSync(path)).digest('hex')!==expected)throw Error('JNA checksum mismatch');return path;
}
function buildTarget(target,env) {
  run('cargo',['build','--locked','-p','sapflow-ffi','--release','--target',target],env?{env:{...process.env,...env}}:{});
  return join(root,'target',target,'release');
}
