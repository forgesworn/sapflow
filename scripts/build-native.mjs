// Adapted from ForgeSworn Foregather native packaging (MIT).
// All Cargo builds reuse this checkout's target/. Only owned staging is removed.
import {execFileSync} from 'node:child_process';
import {mkdirSync,mkdtempSync,readFileSync,writeFileSync,copyFileSync,rmSync,existsSync,readdirSync,constants} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {join,basename,resolve} from 'node:path';
import {createHash} from 'node:crypto';
import {parseNativeBuildOptions,reserveNativeOutputRoot} from './native-build-options.mjs';
const root=fileURLToPath(new URL('../',import.meta.url));
// Kotlin language/API 2.2 keeps archive metadata compatible with the native app.
const {mode,selectedTargets,packageLabel,outputRoot,customOutputRoot}=parseNativeBuildOptions(root,process.argv.slice(2));
// A custom namespace is one-use and reserved before staging or a build child.
const packageRoot=customOutputRoot?reserveNativeOutputRoot(root,outputRoot):outputRoot;
const run=(file,args,options={})=>execFileSync(file,args,{cwd:root,stdio:'inherit',...options});
const staging=mkdtempSync(join(root,'target/sapflow-native-build-'));
const version=readFileSync(join(root,'Cargo.toml'),'utf8').match(/^version = "([^"]+)"/m)[1];
let output;
function refreshOwned(path) {
  if(customOutputRoot) {
    mkdirSync(path); // A collision is never an excuse to delete another package.
    writeFileSync(join(path,'.sapflow-owned'),'Generated by scripts/build-native.mjs\n',{flag:'wx'});return path;
  }
  if(existsSync(path)&&!existsSync(join(path,'.sapflow-owned')))throw Error('Refusing to replace unowned native output');
  rmSync(path,{recursive:true,force:true});mkdirSync(path,{recursive:true});writeFileSync(join(path,'.sapflow-owned'),'Generated by scripts/build-native.mjs\n');return path;
}
function buildHostJni() {
  const javaHome=process.env.JAVA_HOME??run('/usr/libexec/java_home',[],{stdio:'pipe',encoding:'utf8'}).trim();
  const output=join(root,`target/debug/libsapflow_jni.${process.platform==='darwin'?'dylib':'so'}`);
  run('clang',['-O2','-Wall','-Wextra','-Werror','-fPIC',process.platform==='darwin'?'-dynamiclib':'-shared',
    `-I${join(javaHome,'include')}`,`-I${join(javaHome,'include',process.platform==='darwin'?'darwin':'linux')}`,
    join(root,'crates/sapflow-ffi/jni/sapflow_jni.c'),'-L',join(root,'target/debug'),'-lsapflow_ffi',
    `-Wl,-rpath,${join(root,'target/debug')}`,'-o',output]);
  return output;
}
function buildTarget(target,env) {
  run('cargo',['build','--locked','-p','sapflow-ffi','--release','--target',target],env?{env:{...process.env,...env}}:{});
  return join(root,'target',target,'release');
}
try {
  run('cargo',['build','--locked','-p','sapflow-ffi']);
  copyFileSync(join(root,'crates/sapflow-ffi/swift/Sapflow.swift'),join(staging,'Sapflow.swift'));
  copyFileSync(join(root,'crates/sapflow-ffi/include/SapflowFFI.h'),join(staging,'SapflowFFI.h'));
  copyFileSync(join(root,'crates/sapflow-ffi/include/module.modulemap'),join(staging,'SapflowFFI.modulemap'));
  const kotlin=join(staging,'sapflow_capi.kt');
  copyFileSync(join(root,'crates/sapflow-ffi/kotlin/dev/forgesworn/sapflow/sapflow_capi.kt'),kotlin);
  buildHostJni();
  if(mode==='check') {
    if(process.platform==='darwin') {
      const macosSDK=run('/usr/bin/xcrun',['--sdk','macosx','--show-sdk-path'],{stdio:'pipe',encoding:'utf8'}).trim();
      copyFileSync(join(root,'tests/native/consumer.swift'),join(staging,'main.swift'));
      run('/usr/bin/xcrun',['--sdk','macosx','swiftc',join(staging,'Sapflow.swift'),join(staging,'main.swift'),'-sdk',macosSDK,'-I',staging,'-Xcc',`-fmodule-map-file=${join(staging,'SapflowFFI.modulemap')}`,'-L',join(root,'target/debug'),'-lsapflow_ffi','-Xlinker','-rpath','-Xlinker',join(root,'target/debug'),'-o',join(staging,'swift-consumer')],{env:{...process.env,SDKROOT:macosSDK}});
      run(join(staging,'swift-consumer'),[]);
    }
    run('kotlinc',['-language-version','2.2','-api-version','2.2',kotlin,join(root,'tests/native/Consumer.kt'),'-include-runtime','-jvm-target','1.8','-d',join(staging,'kotlin-consumer.jar')]);
    run('java',[`-Djava.library.path=${staging}:${join(root,'target/debug')}`,'-cp',join(staging,'kotlin-consumer.jar'),'ConsumerKt']);
    console.log(JSON.stringify({passed:true,nativeConsumers:true,swift:process.platform==='darwin',kotlin:true,handwrittenTransport:true,jnaRequired:false,temporaryStagingRemoved:true}));
  } else if(mode==='apple') {
    if(process.platform!=='darwin')throw Error('Apple packages require Xcode on macOS');
    output=refreshOwned(join(packageRoot,'apple'));
    const headers=join(staging,'headers');mkdirSync(headers);copyFileSync(join(staging,'SapflowFFI.h'),join(headers,'SapflowFFI.h'));copyFileSync(join(staging,'SapflowFFI.modulemap'),join(headers,'module.modulemap'));
    const libraries=[];
    for(const target of ['aarch64-apple-darwin','aarch64-apple-ios','aarch64-apple-ios-sim'])libraries.push('-library',join(buildTarget(target),'libsapflow_ffi.a'),'-headers',headers);
    run('xcodebuild',['-create-xcframework',...libraries,'-output',join(output,'SapflowFFI.xcframework')]);
    const sources=join(output,'Sources/Sapflow');mkdirSync(sources,{recursive:true});copyFileSync(join(staging,'Sapflow.swift'),join(sources,'Sapflow.swift'));
    writeFileSync(join(output,'Package.swift'),`// swift-tools-version: 5.9\nimport PackageDescription\nlet package = Package(name:"Sapflow",platforms:[.iOS(.v15),.macOS(.v12)],products:[.library(name:"Sapflow",targets:["Sapflow"])],targets:[.binaryTarget(name:"SapflowFFI",path:"SapflowFFI.xcframework"),.target(name:"Sapflow",dependencies:["SapflowFFI"])])\n`);
    run('swift',['build','--package-path',output,'--scratch-path',join(staging,'swift-build')]);
    const consumer=join(staging,'consumer'),consumerSource=join(consumer,'Sources/NativeCheck');mkdirSync(consumerSource,{recursive:true});
    writeFileSync(join(consumer,'Package.swift'),`// swift-tools-version: 5.9\nimport PackageDescription\nlet package=Package(name:"NativeCheck",platforms:[.macOS(.v12)],dependencies:[.package(name:"Sapflow",path:${JSON.stringify(output)})],targets:[.executableTarget(name:"NativeCheck",dependencies:[.product(name:"Sapflow",package:"Sapflow")])])\n`);
    writeFileSync(join(consumerSource,'main.swift'),`import Sapflow\n${readFileSync(join(root,'tests/native/consumer.swift'),'utf8')}`);
    // Keep scratch outside the package path's textual prefix: SwiftPM debug
    // prefix mapping otherwise turns consumer-build into consumer/-build.
    run('swift',['run','--package-path',consumer,'--scratch-path',join(staging,'installed-check-build'),'NativeCheck']);
    writeFileSync(join(output,'README.md'),'Sapflow Swift package. Add this directory as a local Swift package. Requires iOS 15/macOS 12; this build contains ARM64 macOS, iOS and iOS Simulator slices. Broadcaster integration and physical-device qualification remain in progress. See the bundled dependency licences and the source delivery plan.\n');
  } else {
    output=refreshOwned(join(packageRoot,packageLabel));
    const aar=join(staging,'aar');mkdirSync(aar);run('kotlinc',['-language-version','2.2','-api-version','2.2',kotlin,'-jvm-target','1.8','-d',join(aar,'classes.jar')]);
    const ndk=process.env.ANDROID_NDK_HOME??join(process.env.ANDROID_HOME??join(process.env.HOME,'Library/Android/sdk'),'ndk/27.1.12297006');
    const prebuilt=join(ndk,'toolchains/llvm/prebuilt',process.platform==='darwin'?'darwin-x86_64':'linux-x86_64');
    const toolchain=join(prebuilt,'bin'),sysroot=join(prebuilt,'sysroot');
    for(const [target,abi,compiler] of selectedTargets) {
      const linker=join(toolchain,compiler);if(!existsSync(linker))throw Error('Configure ANDROID_NDK_HOME with an installed NDK');
      const targetKey=target.toUpperCase().replaceAll('-','_');
      const env={[`CARGO_TARGET_${targetKey}_LINKER`]:linker,[`CARGO_TARGET_${targetKey}_RUSTFLAGS`]:'-C link-arg=-Wl,-z,max-page-size=16384'};
      const directory=buildTarget(target,env),destination=join(aar,'jni',abi);mkdirSync(destination,{recursive:true});copyFileSync(join(directory,'libsapflow_ffi.so'),join(destination,'libsapflow_ffi.so'));
      run(linker,['-O2','-Wall','-Wextra','-Werror','-fPIC','-shared',`-I${join(sysroot,'usr/include')}`,
        join(root,'crates/sapflow-ffi/jni/sapflow_jni.c'),'-L',directory,'-lsapflow_ffi',
        '-Wl,-z,max-page-size=16384','-o',join(destination,'libsapflow_jni.so')]);
    }
    writeFileSync(join(aar,'AndroidManifest.xml'),'<manifest xmlns:android="http://schemas.android.com/apk/res/android" package="dev.forgesworn.sapflow"><uses-sdk android:minSdkVersion="23"/></manifest>\n');
    // JNI resolves the native entry-point class and methods by name.
    const consumerRules='-keep class dev.forgesworn.sapflow.** { *; }\n';
    writeFileSync(join(aar,'proguard.txt'),consumerRules);
    const meta=join(aar,'META-INF');mkdirSync(meta);copyFileSync(join(root,'LICENSE'),join(meta,'LICENSE'));run('python3',['scripts/third-party-licences.py','--package','sapflow-ffi','--output',join(meta,'THIRD_PARTY_LICENSES.txt')]);
    const outputAar=join(output,`sapflow-${version}.aar`),packedAar=customOutputRoot?join(staging,`sapflow-${version}.aar`):outputAar;
    run('zip',['-q','-r',packedAar,'.'],{cwd:aar});
    if(customOutputRoot)copyFileSync(packedAar,outputAar,constants.COPYFILE_EXCL);
    if(run('unzip',['-p',outputAar,'proguard.txt'],{stdio:'pipe',encoding:'utf8'})!==consumerRules)throw Error('AAR consumer JNI rules differ');
    const packedClasses=run('unzip',['-p',join(output,`sapflow-${version}.aar`),'classes.jar'],{stdio:'pipe'});const installedClasses=join(staging,'installed-classes.jar');writeFileSync(installedClasses,packedClasses);
    run('kotlinc',['-language-version','2.2','-api-version','2.2',join(root,'tests/native/Consumer.kt'),'-cp',installedClasses,'-include-runtime','-jvm-target','1.8','-d',join(staging,'installed-consumer.jar')]);
    run('java',[`-Djava.library.path=${staging}:${join(root,'target/debug')}`,'-cp',`${join(staging,'installed-consumer.jar')}:${installedClasses}`,'ConsumerKt']);
    copyFileSync(kotlin,join(output,'sapflow_ffi.kt'));
    writeFileSync(join(output,'README.md'),`Sapflow Android AAR, API 23+, ABIs: ${selectedTargets.map(x=>x[1]).join(', ')}. Add the AAR to your application; no JNA dependency is required. Rust and JNI libraries are included for each ABI with 16 KiB page alignment. Consumer ProGuard/R8 rules preserve the JNI facade. Broadcaster integration and physical-device qualification remain in progress. Actual Android devices are a separate qualification gate.\n`);
  }
  if(output) {
    run('python3',['scripts/third-party-licences.py','--package','sapflow-ffi','--output',join(output,'THIRD_PARTY_LICENSES.txt')]);
    copyFileSync(join(root,'LICENSE'),join(output,'LICENSE'));
    const buildInfo={version,platform:mode,...(mode==='android'?{abis:selectedTargets.map(x=>x[1])}:{}),built:true,installedConsumerPassed:true,physicalDeviceQualified:false};
    writeFileSync(join(output,'build-info.json'),JSON.stringify(buildInfo,null,2)+'\n');
    const archive=join(packageRoot,`sapflow-${packageLabel}-${version}.zip`);
    if(customOutputRoot) {
      const packedArchive=join(staging,basename(archive));
      run('zip',['-q','-r',packedArchive,basename(output)],{cwd:resolve(output,'..')});
      copyFileSync(packedArchive,archive,constants.COPYFILE_EXCL);
    } else {
      rmSync(archive,{force:true});
      run('zip',['-q','-r',archive,basename(output)],{cwd:resolve(output,'..')});
    }
    const checksum=createHash('sha256').update(readFileSync(archive)).digest('hex');
    writeFileSync(join(output,'verification.json'),JSON.stringify({...buildInfo,archive:basename(archive),sha256:checksum},null,2)+'\n');
    console.log(JSON.stringify({nativePackage:archive,sha256:checksum,physicalDeviceQualified:false}));
  }
} finally {rmSync(staging,{recursive:true,force:true});}
