use sapflow_hls::{codec, fmp4, recording_checkpoint as checkpoint};
use std::collections::VecDeque;
use std::sync::{Arc, Mutex, MutexGuard};
use std::time::Duration;

const MAX_SAMPLES: usize = 4096;
const MAX_BYTES: u64 = 16 * 1024 * 1024;

#[derive(Debug, Clone, Copy, PartialEq, Eq, uniffi::Error)]
pub enum NativeRecordingError {
    InvalidConfig,
    InvalidMedia,
    Busy,
    Backpressure,
    Closed,
    MissingTracks,
    Encoding,
}
impl std::fmt::Display for NativeRecordingError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "native recording: {self:?}")
    }
}
impl std::error::Error for NativeRecordingError {}

/// One owned bounded write. Only the final duration header sets rewrite_header.
/// Do not log or serialise media bytes. The generated byte-transfer copies are
/// accounted separately from the existing two fMP4 assembly copies.
#[derive(uniffi::Record)]
pub struct RecordingWrite {
    pub bytes: Vec<u8>,
    pub rewrite_header: bool,
}

/// Explicit native source quantisation, never inferred from the output rate.
#[derive(Debug, Clone, Copy, PartialEq, Eq, uniffi::Enum)]
pub enum NativeRecordingSourceMapping {
    Nearest,
    Floor,
}

/// Actual native generation EOF, delivered after its original coded AUs.
#[derive(Debug, Clone, Copy, PartialEq, Eq, uniffi::Record)]
pub struct NativeAudioGenerationReceipt {
    pub generation: u64,
    pub input_frames: u64,
    pub raw_frames: u64,
    pub zero_frames: u64,
    pub input_rate: u32,
    pub encoded_frames: u64,
    pub leading_frames: u32,
    pub trailing_frames: u32,
    pub source_mapping: NativeRecordingSourceMapping,
}
impl From<NativeAudioGenerationReceipt> for timing::GenerationReceipt {
    fn from(x: NativeAudioGenerationReceipt) -> Self {
        Self {
            generation: x.generation,
            input_frames: x.input_frames,
            raw_frames: x.raw_frames,
            zero_frames: x.zero_frames,
            input_rate: x.input_rate,
            encoded_frames: x.encoded_frames,
            leading_frames: x.leading_frames,
            trailing_frames: x.trailing_frames,
            source_mapping: match x.source_mapping {
                NativeRecordingSourceMapping::Nearest => timing::SourceMapping::Nearest,
                NativeRecordingSourceMapping::Floor => timing::SourceMapping::Floor,
            },
        }
    }
}

