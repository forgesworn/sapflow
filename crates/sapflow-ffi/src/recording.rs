struct State {
    video: Track,
    audio: Track,
    has_video: bool,
    has_audio: bool,
    epoch_ns: u64,
    max_bytes: usize,
    fragment_ns: u64,
    bytes: usize,
    samples: usize,
    fragment_start_ns: Option<u64>,
    fragment_end_ns: Option<u64>,
    video_config: Option<codec::H264Config>,
    audio_config: Option<codec::AacConfig>,
    init_len: Option<usize>,
    output: VecDeque<Output>,
    sequence: u32,
    accepted: u64,
    fragments: u64,
    duration_ns: u64,
    finished: bool,
    native: Option<AudioLedger>,
    native_owner: Arc<()>,
    native_failed: bool,
    native_completion: Option<NativeRecordingCompletion>,
    sealed_audio_units: u64,
    sealed_video_units: u64,
    native_initial_context: Option<NativeInitialContext>,
    native_sealed_fragment_bytes: u64,
}
impl State {
    fn ready(&self) -> bool {
        (!self.has_video || self.video_config.is_some())
            && (!self.has_audio || self.audio_config.is_some())
            && self
                .native
                .as_ref()
                .is_none_or(|ledger| ledger.leading().is_some())
    }
    fn header(&self, duration: Duration) -> Result<Vec<u8>, NativeRecordingError> {
        if self.native.is_some() {
            return Err(NativeRecordingError::InvalidConfig);
        }
        fmp4::init_segment_for_tracks(
            self.video_config.as_ref(),
            self.audio_config.as_ref(),
            duration,
        )
        .map(Vec::from)
        .filter(|bytes| !bytes.is_empty())
        .ok_or(NativeRecordingError::Encoding)
    }
    fn flush(&mut self) -> Result<(), NativeRecordingError> {
        if self.native.is_some() {
            return Err(NativeRecordingError::InvalidConfig);
        }
        if self.samples == 0 {
            return Ok(());
        }
        if self.init_len.is_none() {
            return Err(NativeRecordingError::MissingTracks);
        }
        let mut runs = Vec::with_capacity(2);
        if let Some(base_time) = self.video.base_time {
            runs.push(fmp4::TrackRun {
                track_id: fmp4::VIDEO_TRACK,
                base_time,
                samples: &self.video.samples,
            });
        }
        if let Some(base_time) = self.audio.base_time {
            runs.push(fmp4::TrackRun {
                track_id: fmp4::AUDIO_TRACK,
                base_time,
                samples: &self.audio.samples,
            });
        }
        let next_sequence = self
            .sequence
            .checked_add(1)
            .ok_or(NativeRecordingError::Encoding)?;
        let bytes = fmp4::encode_part(self.sequence, &runs);
        if bytes.is_empty() {
            return Err(NativeRecordingError::Encoding);
        }
        let checkpoint = None;
        self.output.push_back(Output::new(
            Vec::from(bytes),
            NativeRecordingChunkKind::Fragment,
            checkpoint,
        ));
        self.sequence = next_sequence;
        self.fragments = self.fragments.saturating_add(1);
        self.video.samples.clear();
        self.audio.samples.clear();
        self.video.base_time = None;
        self.audio.base_time = None;
        self.bytes = 0;
        self.samples = 0;
        self.fragment_start_ns = None;
        self.fragment_end_ns = None;
        Ok(())
    }
    fn native_header_at(
        &self,
        audio_units: u64,
        trailing: u32,
    ) -> Result<Vec<u8>, NativeRecordingError> {
        let ledger = self
            .native
            .as_ref()
            .ok_or(NativeRecordingError::InvalidConfig)?;
        let value = RecordingPresentation {
            audio_start: self
                .audio
                .first_time
                .ok_or(NativeRecordingError::MissingTracks)?,
            audio_frames: audio_units
                .checked_mul(1024)
                .ok_or(NativeRecordingError::Encoding)?,
            leading_frames: ledger.leading().ok_or(NativeRecordingError::InvalidMedia)?,
            trailing_frames: trailing,
            video_start: self.video.first_time,
            video_end: self.has_video.then_some(self.video.presentation_end),
        };
        fmp4::init_segment_for_native_recording(
            self.video_config.as_ref(),
            self.audio_config
                .as_ref()
                .ok_or(NativeRecordingError::MissingTracks)?,
            &value,
        )
        .map(Vec::from)
        .map_err(|_| NativeRecordingError::Encoding)
    }
    /// Serialization and every fallible check precede the output/counter commit.
    fn plan_native_flush(
        &self,
        mode: NativeFlushMode,
    ) -> Result<NativeFlushPlan, NativeRecordingError> {
        let keep = usize::from(
            matches!(
                mode,
                NativeFlushMode::Live {
                    release_audio_tail: false
                }
            ) && !self.audio.samples.is_empty(),
        );
        let audio_take = self.audio.samples.len() - keep;
        let video_take = self.video.samples.len();
        let audio_units = self
            .sealed_audio_units
            .checked_add(audio_take as u64)
            .ok_or(NativeRecordingError::Encoding)?;
        let video_units = self
            .sealed_video_units
            .checked_add(video_take as u64)
            .ok_or(NativeRecordingError::Encoding)?;
        if Some(self.audio.count)
            != self
                .sealed_audio_units
                .checked_add(self.audio.samples.len() as u64)
            || Some(self.video.count)
                != self
                    .sealed_video_units
                    .checked_add(self.video.samples.len() as u64)
        {
            return Err(NativeRecordingError::Encoding);
        }
        let remaining_audio_ns = if keep == 1 {
            let end = self.audio.end.ok_or(NativeRecordingError::Encoding)?;
            let start = end
                .checked_sub(1024)
                .ok_or(NativeRecordingError::Encoding)?;
            let ns = |x: u64| {
                u64::try_from(u128::from(x) * 1_000_000_000 / 48_000)
                    .map_err(|_| NativeRecordingError::Encoding)
            };
            Some((ns(start)?, ns(end)?))
        } else {
            None
        };
        if audio_take + video_take == 0 {
            return Ok(NativeFlushPlan {
                output: None,
                audio_take,
                video_take,
                next_sequence: self.sequence,
                audio_units,
                video_units,
                remaining_audio_ns,
                sealed_fragment_bytes: self.native_sealed_fragment_bytes,
            });
        }
        if self.init_len.is_none() {
            return Err(NativeRecordingError::InvalidMedia);
        }
        let trailing = match mode {
            NativeFlushMode::Complete { trailing } => trailing,
            _ => 0,
        };
        if matches!(mode, NativeFlushMode::Complete { .. })
            && (audio_take == 0 || audio_units != self.audio.count || trailing >= 1024)
        {
            return Err(NativeRecordingError::InvalidMedia);
        }
        let mut runs = Vec::with_capacity(2);
        if video_take > 0 {
            runs.push(fmp4::TrackRun {
                track_id: fmp4::VIDEO_TRACK,
                base_time: self.video.base_time.ok_or(NativeRecordingError::Encoding)?,
                samples: &self.video.samples[..video_take],
            });
        }
        if audio_take > 0 {
            runs.push(fmp4::TrackRun {
                track_id: fmp4::AUDIO_TRACK,
                base_time: self.audio.base_time.ok_or(NativeRecordingError::Encoding)?,
                samples: &self.audio.samples[..audio_take],
            });
        }
        let bytes = match mode {
            NativeFlushMode::Complete { .. } => {
                fmp4::encode_native_recording_part_with_final_audio_duration(
                    self.sequence,
                    &runs,
                    1024 - trailing,
                )
            }
            _ => fmp4::encode_native_recording_part(self.sequence, &runs),
        };
        if bytes.is_empty() {
            return Err(NativeRecordingError::Encoding);
        }
        let ledger = self
            .native
            .as_ref()
            .ok_or(NativeRecordingError::InvalidConfig)?;
        let audio_start = self
            .audio
            .first_time
            .ok_or(NativeRecordingError::MissingTracks)?;
        let coded = audio_units
            .checked_mul(1024)
            .ok_or(NativeRecordingError::Encoding)?;
        let audio_end = audio_start
            .checked_add(coded)
            .ok_or(NativeRecordingError::Encoding)?;
        let audio_container_end = audio_end
            .checked_sub(u64::from(trailing))
            .ok_or(NativeRecordingError::InvalidMedia)?;
        let complete_audio_eof = matches!(mode, NativeFlushMode::Complete { .. })
            && ledger
                .final_receipt()
                .is_some_and(|x| x.encoded_frames == coded);
        let initial_context = self
            .native_initial_context
            .ok_or(NativeRecordingError::Encoding)?;
        let header = self.native_header_at(audio_units, trailing)?;
        if header.len() != initial_context.header_len as usize {
            return Err(NativeRecordingError::Encoding);
        }
        let (sealed_fragment_bytes, sealed_file_end) = sealed_byte_frontier(
            initial_context.header_len,
            self.native_sealed_fragment_bytes,
            bytes.len(),
        )?;
        let checkpoint = Arc::new(NativeRecordingCheckpoint {
            owner: self.native_owner.clone(),
            header,
            initial_context,
            fragment_region_bytes: sealed_fragment_bytes,
            sealed_file_end,
            facts: NativeRecordingCheckpointFacts {
                sequence: self.sequence,
                audio_units,
                video_units,
                audio_start,
                audio_end,
                audio_container_end,
                final_trailing_frames: trailing,
                complete_audio_eof,
                video_start: self.video.first_time,
                video_end: self.has_video.then_some(self.video.presentation_end),
                first_leading_frames: ledger.leading().ok_or(NativeRecordingError::InvalidMedia)?,
                completed_generation_count: ledger
                    .completed_generations_through(coded)
                    .map_err(|_| NativeRecordingError::InvalidMedia)?,
            },
        });
        let next_sequence = self
            .sequence
            .checked_add(1)
            .ok_or(NativeRecordingError::Encoding)?;
        Ok(NativeFlushPlan {
            output: Some(Output::new(
                Vec::from(bytes),
                NativeRecordingChunkKind::Fragment,
                Some(checkpoint),
            )),
            audio_take,
            video_take,
            next_sequence,
            audio_units,
            video_units,
            remaining_audio_ns,
            sealed_fragment_bytes,
        })
    }
    fn commit_native_flush(&mut self, plan: NativeFlushPlan) {
        if let Some(output) = plan.output {
            self.output.push_back(output);
            self.sequence = plan.next_sequence;
            self.native_sealed_fragment_bytes = plan.sealed_fragment_bytes;
            self.fragments = self.fragments.saturating_add(1);
        }
        self.audio.samples.drain(..plan.audio_take);
        self.video.samples.drain(..plan.video_take);
        self.sealed_audio_units = plan.audio_units;
        self.sealed_video_units = plan.video_units;
        self.audio.base_time = if self.audio.samples.is_empty() {
            None
        } else {
            self.audio.end.and_then(|x| x.checked_sub(1024))
        };
        self.video.base_time = None;
        self.bytes = self.audio.samples.iter().map(|x| x.data.len()).sum();
        self.samples = self.audio.samples.len();
        self.fragment_start_ns = plan.remaining_audio_ns.map(|x| x.0);
        self.fragment_end_ns = plan.remaining_audio_ns.map(|x| x.1);
    }
    fn accept_native(&mut self, input: NativeInput) -> Result<(), NativeRecordingError> {
        let is_video = input.sample.is_video();
        // Parse candidate configuration before it can prove an older held AU non-final.
        let new_video = match input.sample.config().as_ref() {
            CodecConfig::H264(config) if self.video_config.is_none() => Some(
                codec::H264Config::new(config.sps(), config.pps())
                    .ok_or(NativeRecordingError::InvalidMedia)?,
            ),
            _ => None,
        };
        let new_audio = match input.sample.config().as_ref() {
            CodecConfig::Aac(config) if self.audio_config.is_none() => Some(
                codec::AacConfig::from_audio_specific_config(&config.audio_specific_config())
                    .ok_or(NativeRecordingError::InvalidMedia)?,
            ),
            _ => None,
        };
        let first_audio = self.audio.first_time.or((!is_video).then_some(input.dts));
        let first_video = self.video.first_time.or(is_video.then_some(input.dts));
        let video_config = self.video_config.as_ref().or(new_video.as_ref());
        let audio_config = self.audio_config.as_ref().or(new_audio.as_ref());
        let initial = if self.init_len.is_none()
            && (!self.has_video || video_config.is_some())
            && audio_config.is_some()
        {
            let leading = self
                .native
                .as_ref()
                .and_then(AudioLedger::leading)
                .ok_or(NativeRecordingError::InvalidMedia)?;
            let value = RecordingPresentation {
                audio_start: first_audio.ok_or(NativeRecordingError::InvalidMedia)?,
                audio_frames: 0,
                leading_frames: leading,
                trailing_frames: 0,
                video_start: first_video,
                video_end: first_video,
            };
            Some(
                fmp4::init_segment_for_native_recording(
                    video_config,
                    audio_config.ok_or(NativeRecordingError::InvalidMedia)?,
                    &value,
                )
                .map(Vec::from)
                .map_err(|_| NativeRecordingError::Encoding)?,
            )
        } else {
            None
        };
        let initial_context = initial
            .as_ref()
            .map(|header| {
                Ok::<_, NativeRecordingError>(NativeInitialContext {
                    header_len: u32::try_from(header.len())
                        .map_err(|_| NativeRecordingError::Encoding)?,
                    header_sha256: checkpoint::metadata_sha256(header),
                    media_epoch_ns: self.epoch_ns,
                })
            })
            .transpose()?;
        let bytes = self
            .bytes
            .checked_add(input.sample.payload().len())
            .ok_or(NativeRecordingError::Encoding)?;
        let start = self
            .fragment_start_ns
            .map_or(input.now_ns, |x| x.min(input.now_ns));
        let end = self
            .fragment_end_ns
            .map_or(input.relative_end, |x| x.max(input.relative_end));
        let needs_flush = self.samples > 0
            && (input.gap
                || end.saturating_sub(start) > self.fragment_ns
                || bytes > self.max_bytes
                || self.samples >= MAX_SAMPLES);
        let plan = if needs_flush {
            Some(self.plan_native_flush(NativeFlushMode::Live {
                release_audio_tail: !is_video,
            })?)
        } else {
            None
        };
        let (remaining_bytes, remaining_samples, remaining_ns) = if let Some(plan) = &plan {
            (
                self.audio.samples[plan.audio_take..]
                    .iter()
                    .map(|x| x.data.len())
                    .sum::<usize>(),
                self.audio.samples.len() - plan.audio_take,
                plan.remaining_audio_ns,
            )
        } else {
            (
                self.bytes,
                self.samples,
                self.fragment_start_ns.zip(self.fragment_end_ns),
            )
        };
        let after_start = remaining_ns.map_or(input.now_ns, |x| x.0.min(input.now_ns));
        let after_end = remaining_ns.map_or(input.relative_end, |x| x.1.max(input.relative_end));
        if remaining_bytes
            .checked_add(input.sample.payload().len())
            .is_none_or(|x| x > self.max_bytes)
            || remaining_samples >= MAX_SAMPLES
            || after_end.saturating_sub(after_start) > self.fragment_ns
        {
            return Err(NativeRecordingError::InvalidMedia);
        }
        // Reserve before committing output. The single held entry stays in this same vector.
        if is_video {
            self.video.samples.try_reserve(1)
        } else {
            self.audio.samples.try_reserve(1)
        }
        .map_err(|_| NativeRecordingError::Encoding)?;
        self.output
            .try_reserve(2)
            .map_err(|_| NativeRecordingError::Encoding)?;
        if let Some(plan) = plan {
            self.commit_native_flush(plan);
        }
        if let Some(header) = initial {
            self.native_initial_context = initial_context;
            self.init_len = Some(header.len());
            self.output
                .push_back(Output::new(header, NativeRecordingChunkKind::Initial, None));
        }
        if let Some(config) = new_video {
            self.video_config = Some(config);
        }
        if let Some(config) = new_audio {
            self.audio_config = Some(config);
        }
        let track = if is_video {
            &mut self.video
        } else {
            &mut self.audio
        };
        track
            .config
            .get_or_insert_with(|| input.sample.config().clone());
        track.end = Some(input.end);
        track.first_time.get_or_insert(input.dts);
        track.count = input.next_count;
        track.presentation_end = track.presentation_end.max(input.track_presentation_end);
        track.base_time.get_or_insert(input.dts);
        let sync = !is_video || input.sample.is_keyframe();
        track.samples.push(fmp4::Sample {
            duration: input.duration,
            cts: input.cts,
            sync,
            data: Bytes::from_owner(EncodedPayload(input.sample)),
        });
        self.bytes = remaining_bytes + track.samples.last().map_or(0, |x| x.data.len());
        self.samples = remaining_samples + 1;
        self.fragment_start_ns = Some(after_start);
        self.fragment_end_ns = Some(after_end);
        self.duration_ns = self.duration_ns.max(input.presentation_end);
        self.accepted = self.accepted.saturating_add(1);
        Ok(())
    }
    fn push(&mut self, sample: SharedSample) -> Result<(), NativeRecordingError> {
        if self.finished {
            return Err(NativeRecordingError::Closed);
        }
        if self.native_failed {
            return Err(NativeRecordingError::InvalidMedia);
        }
        if !self.output.is_empty() {
            return Err(NativeRecordingError::Backpressure);
        }
        let is_video = sample.is_video();
        if (is_video && !self.has_video)
            || (!is_video && !self.has_audio)
            || sample.payload().len() > self.max_bytes
        {
            return Err(NativeRecordingError::InvalidMedia);
        }
        let timing = sample.timing();
        if !is_video
            && self
                .native
                .as_ref()
                .is_some_and(|x| x.final_receipt().is_some())
        {
            return Err(NativeRecordingError::InvalidMedia);
        }
        if self.native.is_some()
            && (timing.pts() != timing.dts()
                || (!is_video
                    && (self
                        .native
                        .as_ref()
                        .and_then(AudioLedger::leading)
                        .is_none()
                        || !matches!(sample.config().as_ref(), CodecConfig::Aac(config) if config.audio_specific_config() == [0x11, 0x88])
                        || timing.timescale() != 48_000
                        || timing.duration() != 1024)))
        {
            return Err(NativeRecordingError::InvalidMedia);
        }
        let target = match sample.config().as_ref() {
            CodecConfig::H264(_) => fmp4::VIDEO_TIMESCALE,
            // The existing mp4a sample entry uses a 16.16 rate field.
            // Refuse unsupported high-rate entries rather than silently clamp.
            CodecConfig::Aac(config) if config.sample_rate() <= u32::from(u16::MAX) => {
                config.sample_rate()
            }
            CodecConfig::Aac(_) => return Err(NativeRecordingError::InvalidMedia),
        };
        let epoch = u128::from(self.epoch_ns) * u128::from(target) / 1_000_000_000;
        let scale = |ticks: u128| -> Result<u64, NativeRecordingError> {
            let value = ticks * u128::from(target) / u128::from(timing.timescale());
            u64::try_from(
                value
                    .checked_sub(epoch)
                    .ok_or(NativeRecordingError::InvalidMedia)?,
            )
            .map_err(|_| NativeRecordingError::InvalidMedia)
        };
        let dts = scale(timing.dts() as u128)?;
        let pts = scale(timing.pts() as u128)?;
        let end = scale(timing.dts() as u128 + u128::from(timing.duration()))?;
        let track_presentation_end = scale(timing.pts() as u128 + u128::from(timing.duration()))?;
        let duration = u32::try_from(end - dts)
            .ok()
            .filter(|duration| *duration != 0)
            .ok_or(NativeRecordingError::InvalidMedia)?;
        let cts = i32::try_from(i128::from(pts) - i128::from(dts))
            .map_err(|_| NativeRecordingError::InvalidMedia)?;
        let track = if is_video { &self.video } else { &self.audio };
        if self.native.is_some() && !is_video && track.end.is_some_and(|previous| previous != dts) {
            return Err(NativeRecordingError::InvalidMedia);
        }
        let next_count = track
            .count
            .checked_add(1)
            .ok_or(NativeRecordingError::Encoding)?;
        if let Some(config) = &track.config {
            if !Arc::ptr_eq(config, sample.config())
                || track.end.is_some_and(|previous| dts < previous)
            {
                return Err(NativeRecordingError::InvalidMedia);
            }
        } else if is_video && !sample.is_keyframe() {
            return Err(NativeRecordingError::InvalidMedia);
        }
        let gap = track.end.is_some_and(|previous| dts > previous);
        let now_ns = timing
            .decode_time_ns()
            .checked_sub(self.epoch_ns)
            .ok_or(NativeRecordingError::InvalidMedia)?;
        let decode_end_ns = timing
            .decode_end_ns()
            .map_err(|_| NativeRecordingError::InvalidMedia)?;
        let duration_ns = decode_end_ns - timing.decode_time_ns();
        if duration_ns > self.fragment_ns {
            return Err(NativeRecordingError::InvalidMedia);
        }
        let presentation_end = timing
            .presentation_end_ns()
            .map_err(|_| NativeRecordingError::InvalidMedia)?
            .checked_sub(self.epoch_ns)
            .ok_or(NativeRecordingError::InvalidMedia)?;
        let relative_end = now_ns.saturating_add(duration_ns);
        if self.native.is_some() {
            return self.accept_native(NativeInput {
                sample,
                dts,
                end,
                duration,
                cts,
                next_count,
                now_ns,
                relative_end,
                presentation_end,
                track_presentation_end,
                gap,
            });
        }
        let span_start = self
            .fragment_start_ns
            .map_or(now_ns, |start| start.min(now_ns));
        let span_end = self
            .fragment_end_ns
            .map_or(relative_end, |end| end.max(relative_end));
        let span = span_end.saturating_sub(span_start);
        if self.samples > 0
            && (gap
                || span > self.fragment_ns
                || self.bytes + sample.payload().len() > self.max_bytes
                || self.samples >= MAX_SAMPLES)
        {
            self.flush()?;
        }
        match sample.config().as_ref() {
            CodecConfig::H264(config) if self.video_config.is_none() => {
                self.video_config = Some(
                    codec::H264Config::new(config.sps(), config.pps())
                        .ok_or(NativeRecordingError::InvalidMedia)?,
                );
            }
            CodecConfig::Aac(config) if self.audio_config.is_none() => {
                self.audio_config =
                    codec::AacConfig::from_audio_specific_config(&config.audio_specific_config());
                if self.audio_config.is_none() {
                    return Err(NativeRecordingError::InvalidMedia);
                }
            }
            _ => {}
        }
        let track = if is_video {
            &mut self.video
        } else {
            &mut self.audio
        };
        track.config.get_or_insert_with(|| sample.config().clone());
        track.end = Some(end);
        track.first_time.get_or_insert(dts);
        track.count = next_count;
        // Preserve actual presentation extent separately from decode cadence.
        track.presentation_end = track.presentation_end.max(track_presentation_end);
        self.bytes += sample.payload().len();
        self.samples += 1;
        self.fragment_start_ns = Some(
            self.fragment_start_ns
                .map_or(now_ns, |start| start.min(now_ns)),
        );
        self.fragment_end_ns = Some(
            self.fragment_end_ns
                .map_or(relative_end, |end| end.max(relative_end)),
        );
        track.base_time.get_or_insert(dts);
        let sync = !is_video || sample.is_keyframe();
        track.samples.push(fmp4::Sample {
            duration,
            cts,
            sync,
            data: Bytes::from_owner(EncodedPayload(sample)),
        });
        self.duration_ns = self.duration_ns.max(presentation_end);
        self.accepted = self.accepted.saturating_add(1);
        if self.ready() && self.init_len.is_none() {
            let header = self.header(Duration::ZERO)?;
            self.init_len = Some(header.len());
            self.output
                .push_back(Output::new(header, NativeRecordingChunkKind::Initial, None));
        }
        Ok(())
    }
}

#[derive(uniffi::Object)]
pub struct NativeRecordingMuxer {
    state: Mutex<State>,
}
impl NativeRecordingMuxer {
    fn guard(&self) -> Result<MutexGuard<'_, State>, NativeRecordingError> {
        self.state
            .try_lock()
            .map_err(|_| NativeRecordingError::Busy)
    }
}
#[uniffi::export]
impl NativeRecordingMuxer {
    #[uniffi::constructor]
    pub fn new(
        has_video: bool,
        has_audio: bool,
        media_epoch_ns: u64,
        max_fragment_bytes: u64,
        max_fragment_ms: u32,
    ) -> Result<Arc<Self>, NativeRecordingError> {
        if (!has_video && !has_audio)
            || !(1024..=MAX_BYTES).contains(&max_fragment_bytes)
            || !(100..=5000).contains(&max_fragment_ms)
        {
            return Err(NativeRecordingError::InvalidConfig);
        }
        Ok(Arc::new(Self {
            state: Mutex::new(State {
                video: Track::default(),
                audio: Track::default(),
                has_video,
                has_audio,
                epoch_ns: media_epoch_ns,
                max_bytes: max_fragment_bytes as usize,
                fragment_ns: u64::from(max_fragment_ms) * 1_000_000,
                bytes: 0,
                samples: 0,
                fragment_start_ns: None,
                fragment_end_ns: None,
                video_config: None,
                audio_config: None,
                init_len: None,
                output: VecDeque::new(),
                sequence: 1,
                accepted: 0,
                fragments: 0,
                duration_ns: 0,
                finished: false,
                native: None,
                native_owner: Arc::new(()),
                native_failed: false,
                native_completion: None,
                sealed_audio_units: 0,
                sealed_video_units: 0,
                native_initial_context: None,
                native_sealed_fragment_bytes: 0,
            }),
        }))
    }
    /// Opt in to measured native AAC-48k-mono presentation; no legacy mode changes.
    #[uniffi::constructor]
    pub fn with_native_aac_timing(
        has_video: bool,
        has_audio: bool,
        media_epoch_ns: u64,
        max_fragment_bytes: u64,
        max_fragment_ms: u32,
    ) -> Result<Arc<Self>, NativeRecordingError> {
        if !has_audio {
            return Err(NativeRecordingError::InvalidConfig);
        }
        let mux = Self::new(
            has_video,
            has_audio,
            media_epoch_ns,
            max_fragment_bytes,
            max_fragment_ms,
        )?;
        mux.guard()?.native = Some(AudioLedger::default());
        Ok(mux)
    }
    /// Cold first-head fact. Failure is sticky but preserves the accepted prefix.
    pub fn begin_native_audio(
        &self,
        first_leading_frames: u32,
    ) -> Result<(), NativeRecordingError> {
        let mut state = self.guard()?;
        if state.finished || state.native_failed {
            return Err(NativeRecordingError::Closed);
        }
        let observed = state.audio.count;
        let result = state
            .native
            .as_mut()
            .ok_or(NativeRecordingError::InvalidConfig)?
            .begin(first_leading_frames, observed);
        if result.is_err() {
            state.native_failed = true;
        }
        result.map_err(|_| NativeRecordingError::InvalidMedia)
    }
    /// Cold FIFO native generation EOF, checked against actually accepted AUs.
    pub fn end_native_audio_generation(
        &self,
        receipt: NativeAudioGenerationReceipt,
    ) -> Result<(), NativeRecordingError> {
        let mut state = self.guard()?;
        if state.finished || state.native_failed {
            return Err(NativeRecordingError::Closed);
        }
        let observed = state.audio.count;
        let result = state
            .native
            .as_mut()
            .ok_or(NativeRecordingError::InvalidConfig)?
            .append(receipt.into(), observed);
        if result.is_err() {
            state.native_failed = true;
        }
        result.map_err(|_| NativeRecordingError::InvalidMedia)
    }
    /// Final native aggregate, never inferred from the latest live profile.
    pub fn complete_native_audio(
        &self,
        receipt: NativeAudioFileReceipt,
    ) -> Result<(), NativeRecordingError> {
        let mut state = self.guard()?;
        if state.finished || state.native_failed {
            return Err(NativeRecordingError::Closed);
        }
        let observed = state.audio.count;
        let result = state
            .native
            .as_mut()
            .ok_or(NativeRecordingError::InvalidConfig)?
            .complete(receipt.into(), observed);
        if result.is_err() {
            state.native_failed = true;
        }
        result.map_err(|_| NativeRecordingError::InvalidMedia)
    }
    pub fn push(&self, sample: Arc<MediaSample>) -> Result<(), NativeRecordingError> {
        let mut state = self.guard()?;
        let result = state.push(sample.sample.clone());
        if state.native.is_some()
            && matches!(
                result,
                Err(NativeRecordingError::InvalidMedia | NativeRecordingError::Encoding)
            )
        {
            state.native_failed = true;
        }
        result
    }
    pub fn take_output(&self) -> Result<Option<RecordingWrite>, NativeRecordingError> {
        let mut state = self.guard()?;
        if state.native.is_some() {
            return Err(NativeRecordingError::InvalidConfig);
        }
        Ok(state.output.pop_front().map(|x| x.write))
    }
    /// Drain native-mode output on its sole owner, before the next sample push.
    pub fn take_native_output(&self) -> Result<Option<NativeRecordingChunk>, NativeRecordingError> {
        let mut state = self.guard()?;
        if state.native.is_none() {
            return Err(NativeRecordingError::InvalidConfig);
        }
        Ok(state.output.pop_front().map(|x| NativeRecordingChunk {
            bytes: x.write.bytes,
            kind: x.kind,
            checkpoint: x.checkpoint,
        }))
    }
    /// Return a fixed-size incomplete-prefix header for this exact sealed receipt.
    /// File durability remains the platform owner's responsibility.
    pub fn checkpoint_header(
        &self,
        checkpoint: Arc<NativeRecordingCheckpoint>,
    ) -> Result<Vec<u8>, NativeRecordingError> {
        let state = self.guard()?;
        if state.native.is_none()
            || !Arc::ptr_eq(&state.native_owner, &checkpoint.owner)
            || checkpoint.facts.sequence >= state.sequence
        {
            return Err(NativeRecordingError::InvalidMedia);
        }
        Ok(checkpoint.header.clone())
    }
    /// Encode this exact issued sealed snapshot without caller-supplied offsets.
    /// No file write/sync is implied by native serialization or this checksum.
    pub fn encode_checkpoint(
        &self,
        token: Arc<NativeRecordingCheckpoint>,
        recording_binding: Vec<u8>,
        source_file_binding: Vec<u8>,
        fragment_region_sha256: Vec<u8>,
    ) -> Result<NativeRecordingCheckpointEncoding, RecordingCheckpointError> {
        {
            let state = self.guard().map_err(|_| RecordingCheckpointError::Busy)?;
            if state.native.is_none()
                || !Arc::ptr_eq(&state.native_owner, &token.owner)
                || token.facts.sequence >= state.sequence
            {
                return Err(RecordingCheckpointError::ForeignCheckpoint);
            }
        }
        // The exact old token remains immutable after successor output, finish
        // or cancel. Never substitute the muxer's current byte frontier.
        let info = checkpoint::CheckpointInfo {
            context: checkpoint::CheckpointContext {
                binding: checkpoint::CheckpointBinding {
                    recording: digest32(&recording_binding)?,
                    source_file: digest32(&source_file_binding)?,
                },
                media_epoch_ns: token.initial_context.media_epoch_ns,
                initial_header_len: token.initial_context.header_len,
                initial_header_sha256: token.initial_context.header_sha256,
            },
            facts: token.facts.into(),
            committed_offset: token.sealed_file_end,
            fragment_region_bytes: token.fragment_region_bytes,
            fragment_region_sha256: digest32(&fragment_region_sha256)?,
        };
        let bytes = checkpoint::encode(checkpoint::CheckpointRef {
            info: &info,
            header: &token.header,
        })?;
        Ok(NativeRecordingCheckpointEncoding {
            bytes,
            info: info.into(),
        })
    }

    /// Drain ordinary tail and final rewrite-header output before closing the file.
    /// Call only after all accepted capture samples have reached this worker.
    pub fn finish(&self) -> Result<(), NativeRecordingError> {
        let mut state = self.guard()?;
        if state.native.is_some() {
            return Err(NativeRecordingError::InvalidConfig);
        }
        if state.finished {
            return Ok(());
        }
        if !state.output.is_empty() {
            return Err(NativeRecordingError::Backpressure);
        }
        if state.init_len.is_none() {
            return Err(NativeRecordingError::MissingTracks);
        }
        state.flush()?;
        let header = state.header(Duration::from_millis(state.duration_ns.div_ceil(1_000_000)))?;
        if Some(header.len()) != state.init_len {
            return Err(NativeRecordingError::Encoding);
        }
        state.output.push_back(Output::new(
            header,
            NativeRecordingChunkKind::FinalHeader,
            None,
        ));
        state.finished = true;
        Ok(())
    }
    /// Seal native output with checked EOF or explicitly unknown final padding.
    pub fn finish_native(
        &self,
        outcome: NativeRecordingCompletion,
    ) -> Result<(), NativeRecordingError> {
        let mut state = self.guard()?;
        let ledger = state
            .native
            .as_ref()
            .ok_or(NativeRecordingError::InvalidConfig)?;
        if state.finished {
            return if state.native_completion == Some(outcome) {
                Ok(())
            } else {
                Err(NativeRecordingError::Closed)
            };
        }
        if !state.output.is_empty() {
            return Err(NativeRecordingError::Backpressure);
        }
        if state.init_len.is_none() {
            return Err(NativeRecordingError::MissingTracks);
        }
        if state.native_failed && outcome == NativeRecordingCompletion::Complete {
            return Err(NativeRecordingError::InvalidMedia);
        }
        let trailing = match ledger.trailing(outcome.into(), state.audio.count) {
            Ok(value) => value,
            Err(_) => {
                state.native_failed = true;
                return Err(NativeRecordingError::InvalidMedia);
            }
        };
        // Stage the original-AU EOF interpretation, wire bytes and exact checkpoint
        // before publishing any output or releasing the possibly-final AAC owner.
        let prepared = (|| {
            let header = state.native_header_at(state.audio.count, trailing)?;
            if Some(header.len()) != state.init_len {
                return Err(NativeRecordingError::Encoding);
            }
            let mode = match outcome {
                NativeRecordingCompletion::Complete => NativeFlushMode::Complete { trailing },
                NativeRecordingCompletion::IncompletePrefix => NativeFlushMode::Incomplete,
            };
            let plan = state.plan_native_flush(mode)?;
            state
                .output
                .try_reserve(2)
                .map_err(|_| NativeRecordingError::Encoding)?;
            Ok((header, plan))
        })();
        let (header, plan) = match prepared {
            Ok(value) => value,
            Err(error) => {
                if matches!(
                    error,
                    NativeRecordingError::InvalidMedia | NativeRecordingError::Encoding
                ) {
                    state.native_failed = true;
                }
                return Err(error);
            }
        };
        state.commit_native_flush(plan);
        state.output.push_back(Output::new(
            header,
            NativeRecordingChunkKind::FinalHeader,
            None,
        ));
        state.finished = true;
        state.native_completion = Some(outcome);
        Ok(())
    }
    /// Drops unwritten media and output, preserving any bytes the platform wrote.
    pub fn cancel(&self) -> Result<(), NativeRecordingError> {
        let mut state = self.guard()?;
        state.video.samples.clear();
        state.audio.samples.clear();
        state.output.clear();
        state.bytes = 0;
        state.samples = 0;
        state.finished = true;
        Ok(())
    }
    pub fn stats(&self) -> Result<NativeRecordingStats, NativeRecordingError> {
        let state = self.guard()?;
        Ok(NativeRecordingStats {
            buffered_bytes: state.bytes as u64,
            buffered_samples: state.samples as u64,
            queued_output_bytes: state
                .output
                .iter()
                .map(|chunk| chunk.write.bytes.len() as u64)
                .sum(),
            accepted_samples: state.accepted,
            fragments: state.fragments,
            duration_ms: state.duration_ns.div_ceil(1_000_000),
            finished: state.finished,
        })
    }
}

