//! Bounded worker-only fragmented MP4 recording over shared encoder samples.
//!
//! No file/runtime is owned here. Drain `take_output` after every push/finish.
//! The platform worker writes ordinary chunks in order, and seeks to offset
//! zero for `rewrite_header`. Create the file exclusively; retain any accepted
//! prefix on storage/queue failure. Never invoke this muxer from codec/UI work.

use crate::MediaSample;
use bytes::Bytes;
use sapflow_client::{CodecConfig, SharedSample};
use sapflow_hls::{codec, fmp4};
use std::collections::VecDeque;
use std::sync::{Arc, Mutex, MutexGuard};
use std::time::Duration;

const MAX_SAMPLES: usize = 4096;
const MAX_BYTES: u64 = 16 * 1024 * 1024;

#[derive(Debug, Clone, Copy, PartialEq, Eq, uniffi::Error)]
pub enum NativeRecordingError {
    InvalidConfig,
    InvalidMedia,
    Busy,
    Backpressure,
    Closed,
    MissingTracks,
    Encoding,
}
impl std::fmt::Display for NativeRecordingError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "native recording: {self:?}")
    }
}
impl std::error::Error for NativeRecordingError {}

/// One owned bounded write. Only the final duration header sets rewrite_header.
/// Do not log or serialise media bytes. The generated byte transfer is an
/// separately accounted copies after the existing two fMP4 assembly copies.
#[derive(uniffi::Record)]
pub struct RecordingWrite {
    pub bytes: Vec<u8>,
    pub rewrite_header: bool,
}

#[derive(uniffi::Record)]
pub struct NativeRecordingStats {
    pub buffered_bytes: u64,
    pub buffered_samples: u64,
    pub queued_output_bytes: u64,
    pub accepted_samples: u64,
    pub fragments: u64,
    pub duration_ms: u64,
    pub finished: bool,
}

// Bytes owns only this Arc handle. It never clones the compressed payload.
struct EncodedPayload(SharedSample);
impl AsRef<[u8]> for EncodedPayload {
    fn as_ref(&self) -> &[u8] {
        self.0.payload().as_ref()
    }
}
#[derive(Default)]
struct Track {
    config: Option<Arc<CodecConfig>>,
    end: Option<u64>,
    samples: Vec<fmp4::Sample>,
    base_time: Option<u64>,
}
struct State {
    video: Track,
    audio: Track,
    has_video: bool,
    has_audio: bool,
    epoch_ns: u64,
    max_bytes: usize,
    fragment_ns: u64,
    bytes: usize,
    samples: usize,
    fragment_start_ns: Option<u64>,
    fragment_end_ns: Option<u64>,
    video_config: Option<codec::H264Config>,
    audio_config: Option<codec::AacConfig>,
    init_len: Option<usize>,
    output: VecDeque<RecordingWrite>,
    sequence: u32,
    accepted: u64,
    fragments: u64,
    duration_ns: u64,
    finished: bool,
}
impl State {
    fn ready(&self) -> bool {
        (!self.has_video || self.video_config.is_some())
            && (!self.has_audio || self.audio_config.is_some())
    }
    fn header(&self, duration: Duration) -> Result<Vec<u8>, NativeRecordingError> {
        fmp4::init_segment_for_tracks(
            self.video_config.as_ref(),
            self.audio_config.as_ref(),
            duration,
        )
        .map(Vec::from)
        .filter(|bytes| !bytes.is_empty())
        .ok_or(NativeRecordingError::Encoding)
    }
    fn flush(&mut self) -> Result<(), NativeRecordingError> {
        if self.samples == 0 {
            return Ok(());
        }
        if self.init_len.is_none() {
            return Err(NativeRecordingError::MissingTracks);
        }
        let mut runs = Vec::with_capacity(2);
        if let Some(base_time) = self.video.base_time {
            runs.push(fmp4::TrackRun {
                track_id: fmp4::VIDEO_TRACK,
                base_time,
                samples: &self.video.samples,
            });
        }
        if let Some(base_time) = self.audio.base_time {
            runs.push(fmp4::TrackRun {
                track_id: fmp4::AUDIO_TRACK,
                base_time,
                samples: &self.audio.samples,
            });
        }
        let next_sequence = self
            .sequence
            .checked_add(1)
            .ok_or(NativeRecordingError::Encoding)?;
        let bytes = fmp4::encode_part(self.sequence, &runs);
        if bytes.is_empty() {
            return Err(NativeRecordingError::Encoding);
        }
        self.output.push_back(RecordingWrite {
            bytes: Vec::from(bytes),
            rewrite_header: false,
        });
        self.sequence = next_sequence;
        self.fragments = self.fragments.saturating_add(1);
        self.video.samples.clear();
        self.audio.samples.clear();
        self.video.base_time = None;
        self.audio.base_time = None;
        self.bytes = 0;
        self.samples = 0;
        self.fragment_start_ns = None;
        self.fragment_end_ns = None;
        Ok(())
    }
    fn push(&mut self, sample: SharedSample) -> Result<(), NativeRecordingError> {
        if self.finished {
            return Err(NativeRecordingError::Closed);
        }
        if !self.output.is_empty() {
            return Err(NativeRecordingError::Backpressure);
        }
        let is_video = sample.is_video();
        if (is_video && !self.has_video)
            || (!is_video && !self.has_audio)
            || sample.payload().len() > self.max_bytes
        {
            return Err(NativeRecordingError::InvalidMedia);
        }
        let timing = sample.timing();
        let target = match sample.config().as_ref() {
            CodecConfig::H264(_) => fmp4::VIDEO_TIMESCALE,
            // The existing mp4a sample entry uses a 16.16 rate field.
            // Refuse unsupported high-rate entries rather than silently clamp.
            CodecConfig::Aac(config) if config.sample_rate() <= u32::from(u16::MAX) => {
                config.sample_rate()
            }
            CodecConfig::Aac(_) => return Err(NativeRecordingError::InvalidMedia),
        };
        let epoch = u128::from(self.epoch_ns) * u128::from(target) / 1_000_000_000;
        let scale = |ticks: u128| -> Result<u64, NativeRecordingError> {
            let value = ticks * u128::from(target) / u128::from(timing.timescale());
            u64::try_from(
                value
                    .checked_sub(epoch)
                    .ok_or(NativeRecordingError::InvalidMedia)?,
            )
            .map_err(|_| NativeRecordingError::InvalidMedia)
        };
        let dts = scale(timing.dts() as u128)?;
        let pts = scale(timing.pts() as u128)?;
        let end = scale(timing.dts() as u128 + u128::from(timing.duration()))?;
        let duration = u32::try_from(end - dts)
            .ok()
            .filter(|duration| *duration != 0)
            .ok_or(NativeRecordingError::InvalidMedia)?;
        let cts = i32::try_from(i128::from(pts) - i128::from(dts))
            .map_err(|_| NativeRecordingError::InvalidMedia)?;
        let track = if is_video { &self.video } else { &self.audio };
        if let Some(config) = &track.config {
            if !Arc::ptr_eq(config, sample.config())
                || track.end.is_some_and(|previous| dts < previous)
            {
                return Err(NativeRecordingError::InvalidMedia);
            }
        } else if is_video && !sample.is_keyframe() {
            return Err(NativeRecordingError::InvalidMedia);
        }
        let gap = track.end.is_some_and(|previous| dts > previous);
        let now_ns = timing
            .decode_time_ns()
            .checked_sub(self.epoch_ns)
            .ok_or(NativeRecordingError::InvalidMedia)?;
        let decode_end_ns = timing
            .decode_end_ns()
            .map_err(|_| NativeRecordingError::InvalidMedia)?;
        let duration_ns = decode_end_ns - timing.decode_time_ns();
        if duration_ns > self.fragment_ns {
            return Err(NativeRecordingError::InvalidMedia);
        }
        let presentation_end = timing
            .presentation_end_ns()
            .map_err(|_| NativeRecordingError::InvalidMedia)?
            .checked_sub(self.epoch_ns)
            .ok_or(NativeRecordingError::InvalidMedia)?;
        let relative_end = now_ns.saturating_add(duration_ns);
        let span_start = self
            .fragment_start_ns
            .map_or(now_ns, |start| start.min(now_ns));
        let span_end = self
            .fragment_end_ns
            .map_or(relative_end, |end| end.max(relative_end));
        let span = span_end.saturating_sub(span_start);
        if self.samples > 0
            && (gap
                || span > self.fragment_ns
                || self.bytes + sample.payload().len() > self.max_bytes
                || self.samples >= MAX_SAMPLES)
        {
            self.flush()?;
        }
        match sample.config().as_ref() {
            CodecConfig::H264(config) if self.video_config.is_none() => {
                self.video_config = Some(
                    codec::H264Config::new(config.sps(), config.pps())
                        .ok_or(NativeRecordingError::InvalidMedia)?,
                );
            }
            CodecConfig::Aac(config) if self.audio_config.is_none() => {
                self.audio_config =
                    codec::AacConfig::from_audio_specific_config(&config.audio_specific_config());
                if self.audio_config.is_none() {
                    return Err(NativeRecordingError::InvalidMedia);
                }
            }
            _ => {}
        }
        let track = if is_video {
            &mut self.video
        } else {
            &mut self.audio
        };
        track.config.get_or_insert_with(|| sample.config().clone());
        track.end = Some(end);
        self.bytes += sample.payload().len();
        self.samples += 1;
        self.fragment_start_ns = Some(
            self.fragment_start_ns
                .map_or(now_ns, |start| start.min(now_ns)),
        );
        self.fragment_end_ns = Some(
            self.fragment_end_ns
                .map_or(relative_end, |end| end.max(relative_end)),
        );
        track.base_time.get_or_insert(dts);
        let sync = !is_video || sample.is_keyframe();
        track.samples.push(fmp4::Sample {
            duration,
            cts,
            sync,
            data: Bytes::from_owner(EncodedPayload(sample)),
        });
        self.duration_ns = self.duration_ns.max(presentation_end);
        self.accepted = self.accepted.saturating_add(1);
        if self.ready() && self.init_len.is_none() {
            let header = self.header(Duration::ZERO)?;
            self.init_len = Some(header.len());
            self.output.push_back(RecordingWrite {
                bytes: header,
                rewrite_header: false,
            });
        }
        Ok(())
    }
}

#[derive(uniffi::Object)]
pub struct NativeRecordingMuxer {
    state: Mutex<State>,
}
impl NativeRecordingMuxer {
    fn guard(&self) -> Result<MutexGuard<'_, State>, NativeRecordingError> {
        self.state
            .try_lock()
            .map_err(|_| NativeRecordingError::Busy)
    }
}
#[uniffi::export]
impl NativeRecordingMuxer {
    #[uniffi::constructor]
    pub fn new(
        has_video: bool,
        has_audio: bool,
        media_epoch_ns: u64,
        max_fragment_bytes: u64,
        max_fragment_ms: u32,
    ) -> Result<Arc<Self>, NativeRecordingError> {
        if (!has_video && !has_audio)
            || !(1024..=MAX_BYTES).contains(&max_fragment_bytes)
            || !(100..=5000).contains(&max_fragment_ms)
        {
            return Err(NativeRecordingError::InvalidConfig);
        }
        Ok(Arc::new(Self {
            state: Mutex::new(State {
                video: Track::default(),
                audio: Track::default(),
                has_video,
                has_audio,
                epoch_ns: media_epoch_ns,
                max_bytes: max_fragment_bytes as usize,
                fragment_ns: u64::from(max_fragment_ms) * 1_000_000,
                bytes: 0,
                samples: 0,
                fragment_start_ns: None,
                fragment_end_ns: None,
                video_config: None,
                audio_config: None,
                init_len: None,
                output: VecDeque::new(),
                sequence: 1,
                accepted: 0,
                fragments: 0,
                duration_ns: 0,
                finished: false,
            }),
        }))
    }
    pub fn push(&self, sample: Arc<MediaSample>) -> Result<(), NativeRecordingError> {
        self.guard()?.push(sample.sample.clone())
    }
    pub fn take_output(&self) -> Result<Option<RecordingWrite>, NativeRecordingError> {
        Ok(self.guard()?.output.pop_front())
    }
    /// Drain ordinary tail and final rewrite-header output before closing the file.
    /// Call only after all accepted capture samples have reached this worker.
    pub fn finish(&self) -> Result<(), NativeRecordingError> {
        let mut state = self.guard()?;
        if state.finished {
            return Ok(());
        }
        if !state.output.is_empty() {
            return Err(NativeRecordingError::Backpressure);
        }
        if state.init_len.is_none() {
            return Err(NativeRecordingError::MissingTracks);
        }
        state.flush()?;
        let header = state.header(Duration::from_millis(state.duration_ns.div_ceil(1_000_000)))?;
        if Some(header.len()) != state.init_len {
            return Err(NativeRecordingError::Encoding);
        }
        state.output.push_back(RecordingWrite {
            bytes: header,
            rewrite_header: true,
        });
        state.finished = true;
        Ok(())
    }
    /// Drops unwritten media and output, preserving any bytes the platform wrote.
    pub fn cancel(&self) -> Result<(), NativeRecordingError> {
        let mut state = self.guard()?;
        state.video.samples.clear();
        state.audio.samples.clear();
        state.output.clear();
        state.bytes = 0;
        state.samples = 0;
        state.finished = true;
        Ok(())
    }
    pub fn stats(&self) -> Result<NativeRecordingStats, NativeRecordingError> {
        let state = self.guard()?;
        Ok(NativeRecordingStats {
            buffered_bytes: state.bytes as u64,
            buffered_samples: state.samples as u64,
            queued_output_bytes: state
                .output
                .iter()
                .map(|chunk| chunk.bytes.len() as u64)
                .sum(),
            accepted_samples: state.accepted,
            fragments: state.fragments,
            duration_ms: state.duration_ns.div_ceil(1_000_000),
            finished: state.finished,
        })
    }
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::*;
    use crate::MediaCodec;

    fn audio() -> Arc<MediaCodec> {
        MediaCodec::aac(&[0x11, 0x90]).unwrap()
    }
    fn sample(codec: &MediaCodec, dts: i64) -> Arc<MediaSample> {
        codec
            .sample(&[1, 2, 3], dts, dts, 1024, 48_000, false)
            .unwrap()
    }
    fn mux() -> Arc<NativeRecordingMuxer> {
        NativeRecordingMuxer::new(false, true, 0, 4096, 1000).unwrap()
    }
    fn base_time(chunk: &RecordingWrite) -> u64 {
        let at = chunk
            .bytes
            .windows(4)
            .position(|value| value == b"tfdt")
            .unwrap();
        let version = chunk.bytes[at + 4];
        if version == 1 {
            u64::from_be_bytes(chunk.bytes[at + 8..at + 16].try_into().unwrap())
        } else {
            u64::from(u32::from_be_bytes(
                chunk.bytes[at + 8..at + 12].try_into().unwrap(),
            ))
        }
    }
    #[test]
    fn audio_only_shares_payload_and_final_header_keeps_size() {
        let codec = audio();
        let sample = sample(&codec, 0);
        let mux = mux();
        assert_eq!(Arc::strong_count(&sample.sample), 1);
        mux.push(sample.clone()).unwrap();
        assert_eq!(Arc::strong_count(&sample.sample), 2);
        let header = mux.take_output().unwrap().unwrap();
        assert!(!header.rewrite_header);
        assert!(header.bytes.windows(4).any(|value| value == b"soun"));
        assert!(!header.bytes.windows(4).any(|value| value == b"vide"));
        {
            let state = mux.guard().unwrap();
            assert_eq!(
                state.audio.samples[0].data.as_ptr(),
                sample.sample.payload().as_ptr()
            );
        }
        mux.finish().unwrap();
        assert_eq!(Arc::strong_count(&sample.sample), 1);
        let fragment = mux.take_output().unwrap().unwrap();
        assert_eq!(base_time(&fragment), 0);
        let final_header = mux.take_output().unwrap().unwrap();
        assert!(final_header.rewrite_header);
        assert_eq!(header.bytes.len(), final_header.bytes.len());
        assert_ne!(header.bytes, final_header.bytes);
        assert!(mux.take_output().unwrap().is_none());
        assert_eq!(mux.stats().unwrap().duration_ms, 22);
        assert_eq!(mux.push(sample).unwrap_err(), NativeRecordingError::Closed);
    }
    #[test]
    fn gaps_keep_original_track_time_and_duration_includes_silence() {
        let codec = audio();
        let mux = mux();
        mux.push(sample(&codec, 4800)).unwrap();
        mux.take_output().unwrap().unwrap();
        mux.push(sample(&codec, 48_000)).unwrap();
        let first = mux.take_output().unwrap().unwrap();
        assert_eq!(base_time(&first), 4800);
        mux.finish().unwrap();
        let later = mux.take_output().unwrap().unwrap();
        assert_eq!(base_time(&later), 48_000);
        assert_eq!(mux.stats().unwrap().duration_ms, 1022);
    }
    #[test]
    fn output_backpressure_and_config_replacement_do_not_accept_samples() {
        let codec = audio();
        let mux = mux();
        mux.push(sample(&codec, 0)).unwrap();
        assert_eq!(
            mux.push(sample(&codec, 1024)).unwrap_err(),
            NativeRecordingError::Backpressure
        );
        assert_eq!(mux.stats().unwrap().accepted_samples, 1);
        mux.take_output().unwrap();
        assert_eq!(
            mux.push(sample(&audio(), 1024)).unwrap_err(),
            NativeRecordingError::InvalidMedia
        );
        assert_eq!(mux.stats().unwrap().accepted_samples, 1);
        mux.push(sample(&codec, 1024)).unwrap();
        assert_eq!(mux.stats().unwrap().buffered_samples, 2);
        mux.cancel().unwrap();
        assert_eq!(mux.stats().unwrap().buffered_bytes, 0);
        assert!(mux.take_output().unwrap().is_none());
    }
    #[test]
    fn missing_track_and_busy_fail_without_waiting() {
        let mux = NativeRecordingMuxer::new(true, true, 0, 4096, 1000).unwrap();
        let codec = audio();
        mux.push(sample(&codec, 0)).unwrap();
        assert!(mux.take_output().unwrap().is_none());
        assert_eq!(
            mux.finish().unwrap_err(),
            NativeRecordingError::MissingTracks
        );
        let held = mux.guard().unwrap();
        assert!(matches!(mux.stats(), Err(NativeRecordingError::Busy)));
        drop(held);
        mux.cancel().unwrap();
    }
    #[test]
    fn hard_fragment_byte_bound_flushes_before_adding_next_payload() {
        let codec = audio();
        let mux = NativeRecordingMuxer::new(false, true, 0, 1024, 1000).unwrap();
        let payload = vec![1; 700];
        let a = codec.sample(&payload, 0, 0, 1024, 48_000, false).unwrap();
        let b = codec
            .sample(&payload, 1024, 1024, 1024, 48_000, false)
            .unwrap();
        mux.push(a).unwrap();
        mux.take_output().unwrap();
        mux.push(b).unwrap();
        assert_eq!(mux.stats().unwrap().buffered_bytes, 700);
        assert_eq!(mux.stats().unwrap().fragments, 1);
        assert!(mux.take_output().unwrap().is_some());
    }
    #[test]
    fn fragment_media_span_stays_bounded_before_next_sample_is_added() {
        let codec = audio();
        let mux = NativeRecordingMuxer::new(false, true, 0, 4096, 100).unwrap();
        for index in 0..5 {
            mux.push(sample(&codec, index * 1024)).unwrap();
            while mux.take_output().unwrap().is_some() {}
        }
        let stats = mux.stats().unwrap();
        assert_eq!(stats.fragments, 1);
        assert_eq!(stats.buffered_samples, 1);
    }
    #[test]
    fn unsupported_mp4_sample_entry_rate_is_refused_explicitly() {
        let codec = MediaCodec::aac(&[0x10, 0x90]).unwrap(); // AAC-LC 88.2 kHz.
        let sample = codec.sample(&[1, 2], 0, 0, 1024, 88_200, false).unwrap();
        let mux = mux();
        assert_eq!(
            mux.push(sample).unwrap_err(),
            NativeRecordingError::InvalidMedia
        );
        assert_eq!(mux.stats().unwrap().accepted_samples, 0);
    }
    /// Explicit independent-decoder check, driven by a caller-owned short native
    /// encoded MP4 fixture and ffprobe packet offsets. No fixture or process is
    /// started by the test; ordinary unit tests never touch the filesystem.
    #[test]
    #[ignore = "requires SAPFLOW_RECORDING_PACKET_INDEX, INPUT and OUTPUT fixture paths"]
    fn independent_fixture_muxing() {
        use std::io::{Seek, SeekFrom, Write};
        let index =
            std::fs::read_to_string(std::env::var("SAPFLOW_RECORDING_PACKET_INDEX").unwrap())
                .unwrap();
        let input = std::fs::read(std::env::var("SAPFLOW_RECORDING_INPUT").unwrap()).unwrap();
        assert!(input.len() <= 32 * 1024 * 1024);
        let mut rows = index.lines();
        let unhex = |value: &str| -> Vec<u8> {
            assert_eq!(value.len() % 2, 0);
            (0..value.len())
                .step_by(2)
                .map(|index| u8::from_str_radix(&value[index..index + 2], 16).unwrap())
                .collect()
        };
        let video = rows.next().unwrap();
        let video = if video == "-" {
            None
        } else {
            let (sps, pps, length) = codec::avc_decoder_config(&unhex(video)).unwrap();
            assert_eq!(length, 4);
            Some(MediaCodec::h264(&sps, &pps).unwrap())
        };
        let audio = rows.next().unwrap();
        let audio = if audio == "-" {
            None
        } else {
            Some(MediaCodec::aac(&unhex(audio)).unwrap())
        };
        let mux =
            NativeRecordingMuxer::new(video.is_some(), audio.is_some(), 0, 8 * 1024 * 1024, 1000)
                .unwrap();
        let mut output = std::fs::OpenOptions::new()
            .write(true)
            .create_new(true)
            .open(std::env::var("SAPFLOW_RECORDING_OUTPUT").unwrap())
            .unwrap();
        let drain = |mux: &NativeRecordingMuxer, output: &mut std::fs::File| {
            while let Some(write) = mux.take_output().unwrap() {
                if write.rewrite_header {
                    output.seek(SeekFrom::Start(0)).unwrap();
                }
                output.write_all(&write.bytes).unwrap();
            }
        };
        let mut count = 0;
        for row in rows {
            let fields: Vec<_> = row.split_whitespace().collect();
            assert_eq!(fields.len(), 8);
            let codec = if fields[0] == "v" {
                video.as_ref().unwrap()
            } else {
                audio.as_ref().unwrap()
            };
            let offset: usize = fields[6].parse().unwrap();
            let size: usize = fields[7].parse().unwrap();
            let sample = codec
                .sample(
                    &input[offset..offset + size],
                    fields[1].parse().unwrap(),
                    fields[2].parse().unwrap(),
                    fields[3].parse().unwrap(),
                    fields[4].parse().unwrap(),
                    fields[5] == "1",
                )
                .unwrap();
            mux.push(sample).unwrap();
            drain(&mux, &mut output);
            count += 1;
        }
        mux.finish().unwrap();
        drain(&mux, &mut output);
        output.sync_all().unwrap();
        assert!(count > 0);
        assert_eq!(mux.stats().unwrap().accepted_samples, count);
        eprintln!(
            "fixture recording accepted {count} encoded samples; independent decode required"
        );
    }
    #[test]
    fn explicit_media_epoch_preserves_track_offset_and_rejects_earlier_samples() {
        let codec = audio();
        let mux = NativeRecordingMuxer::new(false, true, 1_000_000_000, 4096, 1000).unwrap();
        assert_eq!(
            mux.push(sample(&codec, 47_999)).unwrap_err(),
            NativeRecordingError::InvalidMedia
        );
        mux.push(sample(&codec, 52_800)).unwrap();
        mux.take_output().unwrap();
        mux.finish().unwrap();
        assert_eq!(base_time(&mux.take_output().unwrap().unwrap()), 4800);
        assert_eq!(mux.stats().unwrap().duration_ms, 122);
    }
}
